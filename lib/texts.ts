type Plain = Record<string, unknown>;

// Fehlt in Sanity ein Text, bleibt der Startwert stehen.
export function mergeTexts<T>(base: T, override: unknown): T {
  if (!override || typeof override !== "object") return base;
  const result: Plain = { ...(base as Plain) };
  for (const key of Object.keys(result)) {
    const value = (override as Plain)[key];
    if (value === undefined || value === null || value === "") continue;
    result[key] = typeof result[key] === "object" ? mergeTexts(result[key], value) : value;
  }
  return result as T;
}
